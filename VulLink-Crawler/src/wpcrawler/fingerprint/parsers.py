def clean_slug(raw: str) -> Optional[str]:
    slug = raw.strip().lower()
    return slug if SLUG_RE.match(slug) else None


def clean_version(raw: Optional[str]) -> Optional[str]:
    if not raw:
        return None
    m = re.match(r"^\s*v?(" + VERSION_RE + r")\s*$", raw)
    return m.group(1) if m else None


# --------------------------------------------------------------------------- HTML

def extract_urls(html: str, base_url: str) -> List[str]:
    """All resource/link URLs in a page (attributes plus wp-content paths inside inline scripts/JSON)."""
    soup = BeautifulSoup(html, "html.parser")
    urls: Set[str] = set()
    for tag in soup.find_all(True):
        for attr in ("src", "href", "data-src", "content"):
            val = tag.get(attr)
            if isinstance(val, str) and ("/" in val or val.startswith("?")):
                urls.add(urljoin(base_url, val.strip()))
        srcset = tag.get("srcset")
        if isinstance(srcset, str):
            for part in srcset.split(","):
                if part.strip():
                    urls.add(urljoin(base_url, part.strip().split(" ")[0]))
    unescaped = html.replace("\\/", "/")
    for m in re.finditer(r"""(?:https?:)?//[^\s"'<>()]+|/wp-(?:content|includes)/[^\s"'<>()]+""", unescaped):
        urls.add(urljoin(base_url, m.group(0)))
    return sorted(urls)


def wp_component_refs(urls: Iterable[str]) -> List[Tuple[str, str, Optional[str], str]]:
    """(type, slug, ver-param, url) for every plugin/theme asset URL."""
    out = []
    for url in urls:
        m = WP_PATH_RE.search(url)
        if not m:
            continue
        slug = clean_slug(m.group(2))
        if not slug:
            continue
        ver = clean_version((parse_qs(urlparse(url).query).get("ver") or [None])[0])
        out.append(("plugin" if m.group(1).lower() == "plugins" else "theme", slug, ver, url))
    return out


def core_asset_versions(urls: Iterable[str]) -> List[Tuple[str, str]]:
    """(version, url) from wp-includes assets, skipping bundled third-party libraries."""
    out = []
    for url in urls:
        m = CORE_ASSET_RE.search(url)
        if not m:
            continue
        path = urlparse(url).path.lower()
        if any(h in path for h in CORE_LIB_HINTS):
            continue
        if NUMERIC_VERSION.match(m.group(1)):
            out.append((m.group(1), url))
    return out


def meta_generators(html: str) -> List[str]:
    soup = BeautifulSoup(html, "html.parser")
    return [m.get("content", "").strip() for m in soup.find_all("meta", attrs={"name": re.compile("^generator$", re.I)})
            if m.get("content")]


def parse_generator(content: str) -> Tuple[str, Optional[str]]:
    """'WooCommerce 8.2.1' -> ('woocommerce', '8.2.1'); 'Elementor 3.24.0; features: ...' -> ('elementor', ...)."""
    first = content.split(";")[0].strip()
    m = re.match(r"^(.*?)[\s-]+v?(?:er:?\s*)?(" + VERSION_RE + r")\b", first, re.I)
    if m:
        return m.group(1).strip().lower(), clean_version(m.group(2))
    return first.lower(), None


def generator_display_name(content: str) -> str:
    """'Elementor 4.4.0; features: ...' -> 'Elementor' (original capitalisation, version stripped)."""
    first = content.split(";")[0].strip()
    m = re.match(r"^(.*?)[\s-]+v?(?:er:?\s*)?" + VERSION_RE + r"\b", first, re.I)
    return (m.group(1) if m else first)[:80]


def html_comments(html: str) -> List[str]:
    soup = BeautifulSoup(html, "html.parser")
    return [str(c) for c in soup.find_all(string=lambda s: isinstance(s, Comment))]


def comment_signatures(html: str) -> List[Tuple[str, Optional[str], str]]:
    """(slug, version, matched text) for known plugin signatures in comments (and raw HTML as fallback)."""
    hits = []
    haystacks = html_comments(html) + [html[-5000:]]  # some cache plugins append text after </html>
    for pattern, slug in COMMENT_SIGNATURES:
        for text in haystacks:
            m = pattern.search(text)
            if m:
                ver = clean_version(m.group(1)) if m.groups() else None
                hits.append((slug, ver, m.group(0)[:120]))
                break
    return hits


def same_host_links(html: str, base_url: str, limit: int = 20) -> List[str]:
    """Internal page links worth crawling (no assets, admin, feeds or logout)."""
    soup = BeautifulSoup(html, "html.parser")
    host = urlparse(base_url).netloc
    skip_ext = re.compile(r"\.(jpe?g|png|gif|webp|svg|ico|pdf|zip|gz|mp4|mp3|css|js|xml|txt|woff2?)$", re.I)
    out: List[str] = []
    for a in soup.find_all("a", href=True):
        url = urljoin(base_url, a["href"]).split("#")[0]
        p = urlparse(url)
        if p.scheme not in ("http", "https") or p.netloc != host:
            continue
        if skip_ext.search(p.path) or any(s in url for s in ("/wp-admin", "wp-login", "/feed", "logout", "/wp-json")):
            continue
        if url not in out and url.rstrip("/") != base_url.rstrip("/"):
            out.append(url)
        if len(out) >= limit:
            break
    return out


# --------------------------------------------------------------------------- headers

def rest_root_from_link_header(link: Optional[str]) -> Optional[str]:
    """Link: <https://site/wp-json/>; rel="https://api.w.org/" (also ?rest_route=/ on plain permalinks)."""
    if not link:
        return None
    m = re.search(r'<([^>]+)>\s*;\s*rel="https://api\.w\.org/"', link)
    return m.group(1) if m else None


SERVER_PATTERNS = [
    (re.compile(r"Apache(?:/(" + VERSION_RE + r"))?", re.I), "apache", "Apache HTTP Server"),
    (re.compile(r"nginx(?:/(" + VERSION_RE + r"))?", re.I), "nginx", "nginx"),
    (re.compile(r"OpenLiteSpeed(?:/(" + VERSION_RE + r"))?", re.I), "openlitespeed", "OpenLiteSpeed"),
    (re.compile(r"LiteSpeed(?:/(" + VERSION_RE + r"))?", re.I), "litespeed", "LiteSpeed Web Server"),
]
CDN_SIGNATURES = {"cloudflare": "Cloudflare", "cloudfront": "Amazon CloudFront", "akamai": "Akamai",
                  "sucuri": "Sucuri", "fastly": "Fastly"}


def server_software(headers: Dict[str, str]) -> List[Tuple[str, str, Optional[str], str]]:
    """(slug, name, version, header) from response headers (keys lower-cased)."""
    out = []
    server = headers.get("server", "")
    for pattern, slug, name in SERVER_PATTERNS:
        m = pattern.search(server)
        if m:
            out.append((slug, name, clean_version(m.group(1)), f"Server: {server}"))
            break
    powered = headers.get("x-powered-by", "")
    m = re.search(r"PHP/(" + VERSION_RE + r")", powered, re.I)
    if m:
        out.append(("php", "PHP", clean_version(m.group(1)), f"X-Powered-By: {powered}"))
    elif "php" in powered.lower():
        out.append(("php", "PHP", None, f"X-Powered-By: {powered}"))
    if "x-litespeed-cache" in headers and not any(s[0] in ("litespeed", "openlitespeed") for s in out):
        out.append(("litespeed", "LiteSpeed Web Server", None, "X-LiteSpeed-Cache header"))
    return out


DISTROS = ("Debian", "Ubuntu", "CentOS", "Red Hat", "Rocky", "AlmaLinux", "Fedora", "Amazon Linux", "SUSE", "deb")


def distro_package(header_value: str) -> Optional[str]:
    """'Apache/2.4.66 (Debian)' -> 'Debian'; PHP's 'PHP/8.1.2-1ubuntu2.14' -> 'Ubuntu'."""
    low = header_value.lower()
    for d in DISTROS:
        if d.lower() in low:
            return "Debian" if d == "deb" else d
    return None


def cdn_in_front(headers: Dict[str, str]) -> Optional[str]:
    blob = " ".join(f"{k}: {v}" for k, v in headers.items()).lower()
    return next((name for key, name in CDN_SIGNATURES.items() if key in blob), None)


