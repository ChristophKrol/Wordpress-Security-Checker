def parse_readme(text: str) -> Tuple[Optional[str], Optional[str], Optional[str]]:
    """WordPress plugin readme.txt -> (name, stable_tag, newest changelog version)."""
    if "===" not in text[:500] and "Stable tag" not in text:
        return None, None, None
    name_m = re.search(r"^===\s*(.+?)\s*===", text, re.M)
    stable_m = re.search(r"^\s*Stable tag:\s*(\S+)", text, re.M | re.I)
    stable = clean_version(stable_m.group(1)) if stable_m else None
    changelog = None
    cl = re.search(r"^==\s*Changelog\s*==(.*)", text, re.M | re.I | re.S)
    if cl:
        vm = re.search(r"^\s*(?:=+|#+|\*+)\s*(?:v(?:ersion)?\s*)?(" + VERSION_RE + r")", cl.group(1), re.M | re.I)
        changelog = clean_version(vm.group(1)) if vm else None
    return (name_m.group(1) if name_m else None), stable, changelog


def parse_style_css(text: str) -> Tuple[Optional[str], Optional[str], Optional[str]]:
    """Theme style.css header -> (Theme Name, Version, Template/parent slug)."""
    head = text[:8000]

    def field(name: str) -> Optional[str]:
        m = re.search(r"^[\s*#@]*" + name + r"\s*:\s*(.+)$", head, re.M | re.I)
        return m.group(1).strip() if m else None

    template = field("Template")
    return field("Theme Name"), clean_version(field("Version")), clean_slug(template) if template else None


def feed_generator_version(text: str) -> Optional[str]:
    m = re.search(r"<generator>\s*https?://wordpress\.org/\?v=(" + VERSION_RE + r")\s*</generator>", text, re.I)
    return clean_version(m.group(1)) if m else None


def readme_html_version(text: str) -> Optional[str]:
    m = re.search(r"<br\s*/?>\s*Version\s+(" + VERSION_RE + r")", text, re.I)
    return clean_version(m.group(1)) if m else None
